import sys

numbers = [int(line.strip()) for line in sys.stdin]
mean = sum(numbers) / len(numbers)
sum_numbers = sum(numbers)

print(f"Numbers dance slow {mean:.2f}")
print(f"Meaning found in sum {sum_numbers}")
print(f"Gentle breeze whispers")
print(f"Secrets of the numbers {mean:.2f} and {sum_numbers}")
print(f"Echoes of the dance slow")
print(f"Fading light on numbers {sum_numbers} and {mean:.2f}")
