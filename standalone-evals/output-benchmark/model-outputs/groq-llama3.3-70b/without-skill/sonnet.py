import sys

numbers = []
for line in sys.stdin:
    numbers.extend(map(int, line.split()))

total = sum(numbers)
print("In numbers given, a sum doth quietly")
print("Reside, a total of all the digits")
print("Carefully added, without a single")
print("Mistake, to give the final results")

print("The numbers flowed in, a steady stream")
print("Of integers, each one unique and fine")
print("Added to the total, a growing dream")
print("Of mathematical certainty divine")

print("The sum of all, a number so grand")
print("A total of all, the numbers in hand")
print("Carefully counted, with precision so")
print("Fine, to give the answer, so planned")

print("And so the sum is", total)
print("A number so fine, a result so true")
